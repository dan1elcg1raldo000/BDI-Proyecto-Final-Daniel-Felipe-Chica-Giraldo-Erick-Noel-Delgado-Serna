"""Genera la entrega PostgreSQL desde el histórico público ya conciliado.

SQLite se usa aquí como área temporal de transformación con la biblioteca estándar;
el motor de ejecución y entrega es PostgreSQL. El SQL generado no depende de SQLite.
"""
from pathlib import Path
import sqlite3,subprocess,sys,tempfile,re,json
P=Path(__file__).resolve().parent;ROOT=P.parent

FUNCTIONS=r'''
CREATE FUNCTION fn_codigo18_paro() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE estado_padre text;
BEGIN
 SELECT estado INTO estado_padre FROM registro_produccion WHERE id=NEW.registro_id FOR UPDATE;
 IF NEW.codigo='18' AND estado_padre='CAPTURA' THEN
  RAISE EXCEPTION 'Código 18 pendiente de aprobación para nuevas capturas' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE FUNCTION fn_codigo18_transicion() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.estado='CAPTURA' AND EXISTS(SELECT 1 FROM paro WHERE registro_id=OLD.id AND codigo='18') THEN
  RAISE EXCEPTION 'Código 18 pendiente de aprobación para nuevas capturas' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE FUNCTION fn_validar_paro() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE padre registro_produccion%ROWTYPE; suma numeric; anterior integer;
BEGIN
 SELECT * INTO padre FROM registro_produccion WHERE id=NEW.registro_id FOR UPDATE;
 anterior:=CASE WHEN TG_OP='UPDATE' THEN OLD.id ELSE NULL END;
 SELECT COALESCE(SUM(minutos),0) INTO suma FROM paro WHERE registro_id=NEW.registro_id AND (anterior IS NULL OR id<>anterior);
 IF padre.estado='CAPTURA' AND NEW.minutos+suma>padre.minutos_base THEN
  RAISE EXCEPTION 'Los paros superan los minutos programados' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE FUNCTION fn_validar_registro() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.estado='CAPTURA' AND (
 NEW.minutos_base<COALESCE((SELECT SUM(minutos) FROM paro WHERE registro_id=OLD.id),0)
 OR NEW.pacas_reales<COALESCE((SELECT SUM(pacas) FROM produccion_hora WHERE registro_id=OLD.id),0)
 OR EXISTS(SELECT 1 FROM produccion_hora WHERE registro_id=OLD.id AND hora_relativa*60>=NEW.minutos_base)) THEN
  RAISE EXCEPTION 'El segmento es menor que su detalle' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE FUNCTION fn_validar_hora() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE padre registro_produccion%ROWTYPE; suma numeric; viejo_reg integer; vieja_hora integer;
BEGIN
 SELECT * INTO padre FROM registro_produccion WHERE id=NEW.registro_id FOR UPDATE;
 IF TG_OP='UPDATE' THEN viejo_reg:=OLD.registro_id;vieja_hora:=OLD.hora_relativa; END IF;
 SELECT COALESCE(SUM(pacas),0) INTO suma FROM produccion_hora
 WHERE registro_id=NEW.registro_id AND (TG_OP='INSERT' OR NOT(registro_id=viejo_reg AND hora_relativa=vieja_hora));
 IF NEW.pacas+suma>padre.pacas_reales OR NEW.hora_relativa*60>=padre.minutos_base THEN
  RAISE EXCEPTION 'Detalle horario fuera del segmento' USING ERRCODE='23514';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER codigo_18_nueva_captura BEFORE INSERT ON paro FOR EACH ROW EXECUTE FUNCTION fn_codigo18_paro();
CREATE TRIGGER codigo_18_modificacion_captura BEFORE UPDATE OF codigo,registro_id ON paro FOR EACH ROW EXECUTE FUNCTION fn_codigo18_paro();
CREATE TRIGGER codigo_18_transicion_captura BEFORE UPDATE OF estado ON registro_produccion FOR EACH ROW EXECUTE FUNCTION fn_codigo18_transicion();
CREATE TRIGGER validar_paro_insert BEFORE INSERT ON paro FOR EACH ROW EXECUTE FUNCTION fn_validar_paro();
CREATE TRIGGER validar_paro_update BEFORE UPDATE OF minutos,registro_id ON paro FOR EACH ROW EXECUTE FUNCTION fn_validar_paro();
CREATE TRIGGER validar_registro_update BEFORE UPDATE OF minutos_base,pacas_reales,estado ON registro_produccion FOR EACH ROW EXECUTE FUNCTION fn_validar_registro();
CREATE TRIGGER validar_hora_insert BEFORE INSERT ON produccion_hora FOR EACH ROW EXECUTE FUNCTION fn_validar_hora();
CREATE TRIGGER validar_hora_update BEFORE UPDATE ON produccion_hora FOR EACH ROW EXECUTE FUNCTION fn_validar_hora();
'''

def pgquery(sql):
 return re.sub(r'substr\((\w+\.)?fecha,',lambda m:'substr('+(m[1] or '')+'fecha::text,',sql)

def schema():
 s=(ROOT/'sql/01_esquema.sql').read_text(encoding='utf-8')
 a=s.index('CREATE TRIGGER');b=s.index('CREATE TABLE staging_xlsm')
 s=s[:a]+s[b:]
 s=s.replace('PRAGMA foreign_keys = ON;','').replace('BEGIN;','').replace('COMMIT;','')
 s=s.replace('id INTEGER PRIMARY KEY','id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
 s=s.replace(' REAL',' NUMERIC')
 s=re.sub(r"fecha TEXT NOT NULL CHECK\(length\(fecha\)=10.*?=fecha\),",'fecha DATE NOT NULL,',s)
 s=s.replace("inicio GLOB '[0-2][0-9]:[0-5][0-9]'","inicio ~ '^[0-2][0-9]:[0-5][0-9]$'")
 s=s.replace("fin GLOB '[0-2][0-9]:[0-5][0-9]'","fin ~ '^[0-2][0-9]:[0-5][0-9]$'")
 s=s.replace("codigo GLOB '[0-9][0-9]'","codigo ~ '^[0-9][0-9]$'")
 s=s.replace("typeof(hora_relativa)='integer' AND ",'')
 s=s.replace('creado_en TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP','creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP')
 s=s.replace('contenido_json TEXT NOT NULL CHECK(json_valid(contenido_json))','contenido_json JSONB NOT NULL')
 return s+'\n'+FUNCTIONS

def literal(v):
 if v is None:return 'NULL'
 if isinstance(v,(int,float)):return str(v)
 return "'"+str(v).replace("'","''")+"'"

def export(con,tables):
 chunks=[]
 for table in tables:
  cols=[r[1] for r in con.execute(f'PRAGMA table_info({table})')]
  rows=con.execute(f'SELECT * FROM {table}').fetchall()
  for start in range(0,len(rows),200):
   values=','.join('('+','.join(literal(v) for v in row)+')' for row in rows[start:start+200])
   chunks.append(f"INSERT INTO {table} ({','.join(cols)}) VALUES\n{values};")
  if 'id' in cols:
   chunks.append(f"SELECT setval(pg_get_serial_sequence('{table}','id'),COALESCE((SELECT MAX(id) FROM {table}),1),EXISTS(SELECT 1 FROM {table}));")
 return '\n'.join(chunks)+'\n'

def main():
 with tempfile.TemporaryDirectory(prefix='bdi_conversion_') as t:
  ref=Path(t)/'referencia.sqlite'
  subprocess.run([sys.executable,str(ROOT/'scripts/reconstruir.py'),'--salida',str(ref)],check=True,capture_output=True)
  con=sqlite3.connect(ref)
  try:
   catalogs=export(con,['fuente','maquina','turno','persona','referencia','codigo_paro','subcodigo_paro'])
   data=export(con,['staging_xlsm','registro_produccion','paro','intervencion','produccion_hora','staging_pdf','incidencia'])
  finally:con.close()
 views=pgquery((ROOT/'sql/04_vistas.sql').read_text(encoding='utf-8'))
 queries=json.loads((ROOT/'datos/consultas.json').read_text(encoding='utf-8'))
 real=[]
 for i,(title,q) in enumerate(queries,1):
  q=pgquery(q).replace(':clase',"'REAL'").replace(':desde',"'2025-01-01'").replace(':hasta',"'2025-04-01'")
  real.append(f'-- Q{i:02}: {title}\n{q}')
 files={'01_esquema.sql':schema(),'02_catalogos.sql':catalogs,'03_carga.sql':data,'04_vistas.sql':views,'05_consultas.sql':'\n\n'.join(real)+'\n','06_dml.sql':(ROOT/'sql/06_dml.sql').read_text(encoding='utf-8').replace('PRAGMA foreign_keys=ON;','').replace('scripts/verificar.py','postgresql/verificar.py')}
 for name,content in files.items():(P/name).write_text(content,encoding='utf-8')
 complete='-- PostgreSQL 18. Ejecutar en una base vacía. No elimina objetos existentes.\nBEGIN;\n'
 complete+='\n'.join(files[n] for n in ['01_esquema.sql','02_catalogos.sql','03_carga.sql','04_vistas.sql'])+'\nCOMMIT;\n'
 (P/'00_PROYECTO_COMPLETO.sql').write_text(complete,encoding='utf-8')
 before='BEGIN;\n'+files['01_esquema.sql']+files['02_catalogos.sql']+files['04_vistas.sql']+'\nCOMMIT;\n'
 (P/'00_ANTES_sin_historico.sql').write_text(before,encoding='utf-8')
 print('Generados esquema, datos públicos, vistas y Q01-Q12 para PostgreSQL.')

if __name__=='__main__':main()
